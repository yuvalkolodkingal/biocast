"""Split-mould negative generator — the printable deliverable.

The team prints the MOULD, not the object (paper Fig. 6: the successful ovoid was
cast as two halves so the parting face is atmosphere during curing). This module
turns any grammar's signed-distance field into a set of printable negatives.

Three decisions here are not cosmetic, and each is computed rather than assumed.

1. PARTING PLANE = TRUE WIDEST CROSS-SECTION, not the equator.
   For the ovoid the egg taper moves the maximum cross-section off centre: the
   widest section of the default ShellParams sits at z = -20.1 mm, where the
   equator (z = 0) is only 95 % of that area. Parting at the equator therefore
   leaves a 1.18 mm re-entrant lip that has to scrape past the mould wall — on a
   green bio-cement body that is a spalled edge, and it is invisible in a render.
   `widest_section` locates the maximum by cross-sectional area on the voxel
   grid, so it works for any grammar without analytic special-casing. For a
   prismatic block every section is equally wide, so the tie is broken on the
   other cost: the plane is placed to MINIMISE DRAW DEPTH, because draft relief
   is proportional to draw depth (see 2).

2. DRAFT IS A DIRECTIONAL CONE SWEEP, AND THE DIRECTION IS NOT A FREE CHOICE.
   The object is the validated design; rescaling it to add draft would silently
   invalidate the wall thickness the drying and oxygen models depend on. Instead
   each mould surface is generated by sweeping the relevant field along the
   release direction at the draft angle — a min-plus/max-plus recursion over
   slices (`cone_sweep`).

   Working out which sweep each surface needs is the load-bearing step, because a
   plausible-looking choice yields a mould that is watertight, correctly sized and
   IMPOSSIBLE TO OPEN. The kinematic condition for a fixed core of radius B(z)
   inside a body whose hole is R_hole(z), when the body is withdrawn toward +z, is

       B(z) <= min over z' <= z of R_hole(z')

   and a running minimum from below is non-increasing. So an INTEGRAL core boss
   can never widen upward: the only drafted solution is a boss that NARROWS toward
   the parting plane. That is why the block's cores come out as an hourglass
   (widest at the block's outer faces, narrowest at mid-height) rather than
   carrying the single monotonic taper `grammars.block` applies for a one-piece
   bottom-draw mould — in a split mould that taper has the wrong sense in the
   lower half.

   The same condition rules out an integral boss for the vessel: the ovoid's
   internal cavity (45 mm across at the parting plane) is wider than its Ø32 bore,
   so a boss constrained by the running minimum would be a straight Ø32 column and
   would leave the cavity unformed — casting a 32 mm wall where 26 mm was
   designed. The vessel therefore needs a LOOSE CORE per half, withdrawn upward
   through the open parting face, drafted by an `erode, down` sweep.

   Where a form already has more natural draft than theta the sweep is the
   identity, so the correction is confined to the flat band around the parting
   plane: for the ovoid it costs ~0.05 mm of cavity oversize, while for the
   prismatic block, whose walls have no natural draft, it costs
   tan(theta) * draw_depth laterally everywhere — which is why the block's web
   must be pre-thickened above the standard 25 mm minimum.

3. THE JAMMING CRITERION SPLITS INTO TWO OPPOSITE RULES.
   Aggregate passages (feed, the open parting face, the plug bore) must clear
   6 x d_max or the mix bridges and starves the mould — the same Zuriguel/Vani
   criterion the object constraints use. Liquid-only drains must do the OPPOSITE:
   they have to retain aggregate while passing the spent cementation solution, so
   they are sized deliberately BELOW the certain-clog ratio (W/d < 3) and bridge
   by design. Sizing a drain at 24 mm does not make it a better drain, it makes
   it a hole the mix falls out of. `check_apertures` classifies every aperture and
   applies the right test to each.
"""
