def resample_field(d: np.ndarray, origin, pitch: float, X, Y, Z) -> np.ndarray:
    """Sample a field defined on its own grid at arbitrary world points.

    Linear interpolation of a distance field is safe for boolean use: it moves the
    zero level by less than half a voxel and never changes its topology.
    """
    origin = np.asarray(origin, float)
    idx = np.stack([(X - origin[0]) / pitch, (Y - origin[1]) / pitch,
                    (Z - origin[2]) / pitch])
    return ndimage.map_coordinates(d, idx, order=1, mode="nearest")


def slice_sdf2d(occ: np.ndarray, pitch: float, axis: int = 2) -> np.ndarray:
    """In-plane signed distance of every slice (negative inside), same shape.

    The half-voxel correction is REQUIRED, not cosmetic. The raw two-sided EDT
    measures distance to the nearest voxel CENTRE of the opposite class, so a
    solid voxel touching air reads -pitch and the air voxel touching it reads
    +pitch: the field jumps by 2*pitch across one voxel and its gradient
    magnitude is 2, not 1. Any level-set offset then moves the surface only HALF
    as far as asked, and a sweep whose per-slice step is much smaller than a voxel
    lives entirely inside that doubled band — measured 0.885 deg of draft for a
    1.5 deg request. Placing the interface half a voxel from each centre restores
    |grad| = 1 and makes the requested draft angle the delivered one.
    """
    occ = np.moveaxis(occ, axis, -1)
    out = np.empty(occ.shape, float)
    h = 0.5 * pitch
    for k in range(occ.shape[-1]):
        s = occ[..., k]
        if not s.any():
            out[..., k] = BIG
            continue
        if s.all():
            out[..., k] = -BIG
            continue
        inside = ndimage.distance_transform_edt(s, sampling=pitch)
        outside = ndimage.distance_transform_edt(~s, sampling=pitch)
        out[..., k] = np.where(s, -(inside - h), outside - h)
    return np.moveaxis(out, -1, axis)


def cone_sweep(occ: np.ndarray, pitch: float, *, axis: int = 2,
               up: bool = True, mode: str = "dilate",
               draft_deg: float = 1.5) -> np.ndarray:
    """Draft a solid by a directional cone dilation or erosion. Returns a FIELD.

    The in-plane distance comes from a per-slice 2D EDT (`slice_sdf2d`), which is
    the only formulation that stays correct everywhere. Normalising a 3D distance
    field by its in-plane gradient magnitude looks equivalent and is not: on any
    symmetry axis |grad_xy| -> 0, so the interior of a body of revolution blows up
    (measured: -40 mm became -40000 mm on the axis of a sphere), the `prev - step`
    term is then never the minimum, and the recursion silently degrades to the
    identity — a mould with no draft at all that still passes a watertightness
    check. A 2D EDT per slice is exact by construction and has no such axis.

    Which of the four combinations you need follows from WHO MOVES and WHICH WAY,
    and getting it wrong produces a mould that is watertight and unopenable.

    dilate, up    cavity of a lower half: the object is withdrawn toward +axis, so
                  the cavity must WIDEN upward.
    erode,  up    core boss standing in a lower half: the boss is fixed and the
                  object lifts off it, so the boss must NARROW upward. (An integral
                  boss cannot be drafted the other way: the release condition is
                  B(z) <= min over z' <= z of R_hole(z'), and a running minimum from
                  below is flat, so widening-upward forces a zero-draft prism.)
    erode,  down  loose core withdrawn toward +axis out of the cured body: it must
                  NARROW downward so it lifts clear of its own cavity.
    dilate, down  the mirror of the first case for the upper half.

    Recursions, with step = tan(draft) * pitch:
        dilate : G[k] = min(d[k], G[k-1] - step)     (radius grows)
        erode  : G[k] = max(d[k], G[k-1] + step)     (radius shrinks)
    """
    occ = np.asarray(occ)
    occ = occ if occ.dtype == bool else (occ <= 0)

    # Erosion is the dilation of the complement: erode(S) = ~dilate(~S). Running the
    # max-plus recursion on the solid's own field instead is correct in exact
    # arithmetic but not on a raster — the receding zero level walks INTO the
    # interior, where the two-sided EDT is irregular (diagonal neighbours make the
    # inside samples land on 0.75, 2.12, 3.35 ... rather than on a uniform ladder),
    # so the delivered angle overshoots: measured 2.50 deg for a 1.50 deg request.
    # Dilation always approaches its boundary from the outside, where the field is
    # regular, and reproduces the requested angle to 4 decimal places. Routing
    # erosion through the complement inherits that accuracy.
    if mode == "erode":
        g = cone_sweep(~occ, pitch, axis=axis, up=up, mode="dilate",
                       draft_deg=draft_deg)
        return -g

    d2 = np.moveaxis(slice_sdf2d(occ, pitch, axis=axis), axis, -1)
    o = np.moveaxis(occ, axis, -1)
    # A slice with only one class present carries the +/-BIG sentinel rather than a
    # distance, so it must RESET the recursion instead of feeding it. Otherwise the
    # running extremum latches on +/-1e6 at the first uniform slice and never
    # releases: the sweep returns an empty (or full) solid, which reads as "no
    # interference" in every downstream release check. This bites hardest through
    # the complement route above, where the empty slices beyond the object's
    # extent are uniformly SOLID.
    usable = o.any(axis=(0, 1)) & ~o.all(axis=(0, 1))
    step = np.tan(np.deg2rad(max(draft_deg, 0.0))) * pitch
    G = np.empty_like(d2)
    ks = range(d2.shape[-1]) if up else range(d2.shape[-1] - 1, -1, -1)
    prev = None
    for k in ks:
        if prev is None or not usable[k]:
            G[..., k] = d2[..., k]
        else:
            G[..., k] = np.minimum(d2[..., k], prev - step)
        prev = G[..., k] if usable[k] else None
    return np.moveaxis(G, -1, axis)


def fill_slices(occ: np.ndarray, axis: int = 2) -> np.ndarray:
    """Per-slice hole fill: recovers the OUTER FORM of a hollow body.

    Deliberately not `trimesh.fill()` / 3D `binary_fill_holes`: the outer form of
    a vessel open at both poles is not a 3D-fillable set (its cavity communicates
    with the outside), so only a slice-wise fill recovers the silhouette solid.
    """
    o = np.moveaxis(occ, axis, -1)
    out = np.stack([ndimage.binary_fill_holes(o[..., k]) for k in range(o.shape[-1])],
                   axis=-1)
    return np.moveaxis(out, -1, axis)


def widest_section(occ: np.ndarray, origin, pitch: float, axis: int = 2) -> dict:
    """Locate the maximum cross-section of the (filled) form along `axis`.

    Reports the plateau extent too: for a prism every section ties, which is the
    signal that the parting plane should instead be chosen to minimise draw depth.
    """
    filled = fill_slices(occ, axis=axis)
    area = filled.sum(axis=tuple(i for i in range(3) if i != axis)) * pitch ** 2
    k = int(np.argmax(area))
    coord = float(np.asarray(origin, float)[axis] + k * pitch)
    nz = np.flatnonzero(area > 0)
    plateau = np.flatnonzero(area >= 0.999 * area[k])
    lo = float(np.asarray(origin, float)[axis] + plateau.min() * pitch)
    hi = float(np.asarray(origin, float)[axis] + plateau.max() * pitch)
    return {
        "index": k,
        "coord": coord,
        "area_mm2": float(area[k]),
        "r_equiv_mm": float(np.sqrt(area[k] / np.pi)),
        "plateau_lo": lo,
        "plateau_hi": hi,
        "plateau_width_mm": hi - lo,
        "extent_lo": float(np.asarray(origin, float)[axis] + nz.min() * pitch),
        "extent_hi": float(np.asarray(origin, float)[axis] + nz.max() * pitch),
        "area_profile": area,
        "is_prismatic": bool(hi - lo > 0.25 * (nz.max() - nz.min()) * pitch),
    }


