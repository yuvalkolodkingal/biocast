def build_shell_mould(p, mp: MouldParams | None = None, pitch: float = 1.25) -> dict:
    """Two-part mould plus two loose cores for a hollow ovoid vessel.

    The parting plane is placed on the COMPUTED widest section, not the equator.
    Cores are loose because an integral boss cannot clear the vessel's cavity
    (see the module docstring); each is withdrawn from its own half, which is
    consistent with the split-mould workflow where the halves cure separately.
    """
    from .grammars import shell
    mp = mp or MouldParams(wall=20.0, draft_deg=2.5, flange=25.0, flange_t=18.0,
                           key_r_frac=0.35, bolt_r_frac=0.78)

    obj_m, d_obj, o_obj, _ = shell.build(p, pitch=pitch, return_field=True)
    occ0 = d_obj <= 0.0
    form0 = fill_slices(occ0, axis=2)
    ws = widest_section(occ0, o_obj, pitch, axis=2)
    parting, r_max = ws["coord"], ws["r_equiv_mm"]
    r_cup = r_max + mp.wall
    z_lo = obj_m.bounds[0][2] - mp.wall
    z_hi = obj_m.bounds[1][2] + mp.wall

    pad = mp.flange + 3 * pitch
    X, Y, Z, origin, sh = sdf.make_grid(
        [-(r_cup + pad), -(r_cup + pad), z_lo - 2 * pitch],
        [r_cup + pad, r_cup + pad, z_hi + 2 * pitch], pitch)
    form = resample_field(sdf.signed_distance_from_binary(form0, pitch),
                          o_obj, pitch, X, Y, Z) <= 0.0
    obj = resample_field(d_obj, o_obj, pitch, X, Y, Z) <= 0.0
    block = cup_flange_block(X, Y, Z, r_cup=r_cup, z_lo=z_lo, z_hi=z_hi,
                             parting=parting, flange=mp.flange,
                             flange_t=mp.flange_t) <= 0.0

    k_part = int(round((parting - origin[2]) / pitch))
    below = np.zeros(sh, bool)
    below[:, :, :k_part] = True
    cav_lo = cone_sweep(form & below, pitch, up=True, mode="dilate",
                        draft_deg=mp.draft_deg) <= 0
    cav_up = cone_sweep(form & ~below, pitch, up=False, mode="dilate",
                        draft_deg=mp.draft_deg) <= 0
    cavity = (cav_lo & below) | (cav_up & ~below)

    gate_d = 26.0
    def _gate(ang):
        ca, sa = np.cos(np.deg2rad(ang)), np.sin(np.deg2rad(ang))
        def f(X, Y, Z):
            u = X * ca + Y * sa
            w = -X * sa + Y * ca
            return np.maximum.reduce([
                np.sqrt(w ** 2 + (Z - parting) ** 2) - gate_d / 2,
                -u, u - (r_cup + mp.flange)])
        return f
    r_drain = 25.0
    def _drain(ang):
        dx = r_drain * np.cos(np.deg2rad(ang))
        dy = r_drain * np.sin(np.deg2rad(ang))
        return lambda X, Y, Z: sdf.sd_cylinder_z(X, Y, Z, mp.drain_d / 2, 1e4,
                                                 center=(dx, dy, 0.0))
    A = assemble(obj_occ=obj, cavity_occ=cavity, block_occ=block, X=X, Y=Y, Z=Z,
                 origin=origin, pitch=pitch, parting=parting, mp=mp, r_ref=r_cup,
                 gate_specs=[_gate(30.0), _gate(210.0)],
                 drain_specs=[_drain(15.0 + i * 360.0 / mp.drain_count)
                              for i in range(mp.drain_count)], square=False)

    hollow = form & ~obj
    core_lo = (cone_sweep(hollow & below, pitch, up=False, mode="erode",
                          draft_deg=mp.draft_deg) <= 0) & below
    core_up = (cone_sweep(hollow & ~below, pitch, up=True, mode="erode",
                          draft_deg=mp.draft_deg) <= 0) & ~below
    A.update(obj=obj, form=form, block=block, cavity_full=cavity, hollow=hollow,
             core_lo=core_lo, core_up=core_up, below=below, origin=origin,
             pitch=pitch, parting=parting, widest=ws, r_cup=r_cup,
             gate_d=gate_d, r_drain=r_drain, mp=mp, obj_mesh=obj_m)
    return A


def build_block_mould(p, mp: MouldParams | None = None, pitch: float = 2.0) -> dict:
    """Two-part mould for a hollow-core masonry unit, parted across the core axis.

    Every section of a prism ties for width, so the parting plane is chosen on the
    other cost — minimum draw depth (H/2 rather than H). Draft is taken by ERODING
    away from the parting plane, so the nominal section is preserved at the parting
    plane and the relief lands on the outer faces, inside ASTM C90's +/-3.2 mm
    dimensional tolerance. That same erosion is what turns the cores into the
    hourglass bosses a split mould requires.
    """
    from .grammars import block
    mp = mp or MouldParams(wall=20.0, draft_deg=1.5, flange=28.0, flange_t=20.0,
                           key_base_d=22.0, key_top_d=15.0, key_h=11.0,
                           key_angles_deg=(30.0, 150.0, 275.0), bolt_d=10.5,
                           bolt_count=6, bolt_r_frac=0.72, key_r_frac=0.30,
                           drain_count=8)
    obj_m, d_obj, o_obj, _ = block.build(p, pitch=pitch, return_field=True)
    hx, hy = p.L / 2 + mp.wall, p.W / 2 + mp.wall
    z_lo, z_hi = -p.H / 2 - mp.wall, p.H / 2 + mp.wall
    parting = 0.0

    pad = mp.flange + 3 * pitch
    X, Y, Z, origin, sh = sdf.make_grid([-(hx + pad), -(hy + pad), z_lo - 2 * pitch],
                                        [hx + pad, hy + pad, z_hi + 2 * pitch], pitch)
    obj = resample_field(d_obj, o_obj, pitch, X, Y, Z) <= 0.0
    block_occ = cup_flange_block(X, Y, Z, r_cup=0.0, z_lo=z_lo, z_hi=z_hi,
                                 parting=parting, flange=mp.flange,
                                 flange_t=mp.flange_t, square=True,
                                 half_x=hx, half_y=hy) <= 0.0
    k_part = int(round((parting - origin[2]) / pitch))
    below = np.zeros(sh, bool)
    below[:, :, :k_part] = True
    cav_lo = cone_sweep(obj & below, pitch, up=False, mode="erode",
                        draft_deg=mp.draft_deg) <= 0
    cav_up = cone_sweep(obj & ~below, pitch, up=True, mode="erode",
                        draft_deg=mp.draft_deg) <= 0
    cavity = (cav_lo & below) | (cav_up & ~below)

    gate_w = 26.0
    def _gate(sgn_y, xc):
        def f(X, Y, Z):
            return np.maximum.reduce([
                np.abs(X - xc) - gate_w / 2, np.abs(Z - parting) - gate_w / 2,
                sgn_y * Y - (hy + mp.flange), -(sgn_y * Y - (p.W / 2 - 6 * pitch))])
        return f
    def _drain(dx, dy):
        return lambda X, Y, Z: sdf.sd_cylinder_z(X, Y, Z, mp.drain_d / 2, 1e4,
                                                 center=(dx, dy, 0.0))
    A = assemble(obj_occ=obj, cavity_occ=cavity, block_occ=block_occ, X=X, Y=Y, Z=Z,
                 origin=origin, pitch=pitch, parting=parting, mp=mp, r_ref=hx,
                 gate_specs=[_gate(s, x) for s in (+1, -1) for x in (-110.0, 110.0)],
                 drain_specs=[_drain(dx, dy) for dx in (-150., -50., 50., 150.)
                              for dy in (-55., 55.)],
                 square=True, half_x=hx, half_y=hy)
    A.update(obj=obj, block=block_occ, cavity_full=cavity, below=below,
             origin=origin, pitch=pitch, parting=parting, mp=mp, obj_mesh=obj_m,
             gate_w=gate_w, draw_depth=p.H / 2,
             relief_per_face=float(np.tan(np.deg2rad(mp.draft_deg)) * p.H / 2))
    return A
