def frustum_field(X, Y, Z, *, r_base: float, r_top: float, z0: float, z1: float,
                  center=(0.0, 0.0)) -> np.ndarray:
    """Approximate field of a truncated cone between z0 (r_base) and z1 (r_top)."""
    t = np.clip((Z - z0) / max(z1 - z0, 1e-9), 0.0, 1.0)
    r = r_base + (r_top - r_base) * t
    rad = np.sqrt((X - center[0]) ** 2 + (Y - center[1]) ** 2)
    return np.maximum(rad - r, np.maximum(z0 - Z, Z - z1))


def ring_positions(n: int, angles_deg, radius: float) -> list[tuple[float, float]]:
    ang = list(angles_deg)[:n] if len(angles_deg) >= n else \
        [i * 360.0 / n for i in range(n)]
    return [(radius * np.cos(np.deg2rad(a)), radius * np.sin(np.deg2rad(a))) for a in ang]


def ring_positions_rect(n: int, angles_deg, half_x: float, half_y: float) -> list:
    """Same angular pattern, projected onto a RECTANGULAR perimeter.

    A circular ring is wrong for a prismatic mould and fails silently: on the
    390 x 190 block a radius sized to clear the long side puts the keys at
    y = 197 mm when the flange only reaches y = 143 mm, so every key lands in air
    and `assemble`'s intersection with the half quietly deletes it. The mould then
    prints with no registration at all while every volume check still closes,
    because a feature that was never there cannot unbalance anything. Projecting
    the same angles onto the rectangle keeps the chirality argument intact while
    guaranteeing the keys sit on material.
    """
    ang = list(angles_deg)[:n] if len(angles_deg) >= n else \
        [i * 360.0 / n for i in range(n)]
    out = []
    for a in ang:
        c, s = np.cos(np.deg2rad(a)), np.sin(np.deg2rad(a))
        t = min(half_x / abs(c) if abs(c) > 1e-9 else np.inf,
                half_y / abs(s) if abs(s) > 1e-9 else np.inf)
        out.append((t * c, t * s))
    return out


def keys_are_chiral(angles_deg, n: int) -> bool:
    """True if a key ring on a CIRCULAR flange admits one mating orientation only.

    Valid for a circular flange, whose symmetry group is the full O(2): the test
    is that the angular gap sequence is invariant under no rotation and under no
    reflection. Use `keys_are_chiral_xy` for any other flange outline — a
    rectangle's symmetry group is only {identity, 180 deg, two mirrors}, so an
    angular pattern that is chiral on a circle can become symmetric once it is
    projected onto the rectangle (measured: (0, 118, 242) deg projects onto the
    390 x 190 flange as a mirror-symmetric triple).
    """
    a = np.sort(np.mod(np.asarray(angles_deg[:n], float), 360.0))
    if len(a) < 3:
        return False
    gaps = np.diff(np.concatenate([a, a[:1] + 360.0]))
    if len(set(np.round(gaps, 3))) == 1:
        return False                      # rotationally symmetric
    for rot in np.arange(0, 360, 0.5):    # mirror + any rotation
        b = np.sort(np.mod(-a + rot, 360.0))
        if np.allclose(np.diff(np.concatenate([b, b[:1] + 360.0])), gaps, atol=1e-6):
            return False
    return True


def keys_are_chiral_xy(pts, *, rectangular: bool = True) -> tuple:
    """Chirality of an explicit key layout, tested against the flange's own group.

    The halves meet face to face, so a candidate mis-assembly is any symmetry of
    the flange outline that maps the key set onto itself. For a rectangle that is
    the 180 deg rotation and the two axis mirrors; testing those four is exact,
    where the circular gap-sequence test is not applicable.
    """
    P = np.asarray(pts, float)

    def same(A, B):
        return (sorted(map(tuple, np.round(A, 3)))
                == sorted(map(tuple, np.round(B, 3))))

    if same(P, -P):
        return False, "180-rotation symmetric"
    if not rectangular:
        return keys_are_chiral(np.degrees(np.arctan2(P[:, 1], P[:, 0])), len(P)), "circular"
    for M in ([[1, 0], [0, -1]], [[-1, 0], [0, 1]]):
        Q = P @ np.asarray(M, float).T
        if same(P, Q):
            return False, "mirror symmetric"
        if same(P, -Q):
            return False, "mirror+180 symmetric"
    return True, "chiral"


# --------------------------------------------------------------------------
# Aperture bookkeeping
# --------------------------------------------------------------------------
@dataclass
class Aperture:
    name: str
    kind: str            # "aggregate" | "liquid"
    clear_mm: float
    note: str = ""


def check_apertures(aps, d_max: float, *, jam_mult: float = 6.0,
                    certain_clog_mult: float = 3.0) -> dict:
    """Apply the correct jamming test to each aperture class.

    aggregate: clear >= jam_mult * d_max (Zuriguel 2005 Rc = 4.94 spheres /
               6.0 angular; below this the mix bridges and starves the feature)
    liquid   : clear <= certain_clog_mult * d_max (Vani 2022: always clogs below
               W/d = 3, which is exactly the retention a drain needs)
    """
    rows, ok = [], True
    for a in aps:
        ratio = a.clear_mm / d_max if d_max > 0 else np.inf
        if a.kind == "aggregate":
            passed = ratio >= jam_mult
            limit, test = jam_mult * d_max, f">= {jam_mult:g} x d_max"
        else:
            passed = ratio <= certain_clog_mult
            limit, test = certain_clog_mult * d_max, f"<= {certain_clog_mult:g} x d_max"
        ok &= passed
        rows.append({"name": a.name, "kind": a.kind, "clear_mm": a.clear_mm,
                     "ratio_over_dmax": float(ratio), "limit_mm": float(limit),
                     "test": test, "passed": bool(passed), "note": a.note})
    return {"all_passed": bool(ok), "d_max": d_max, "apertures": rows}


# --------------------------------------------------------------------------
# Verification
# --------------------------------------------------------------------------
def release_sweep(piece: np.ndarray, obj: np.ndarray, *, axis: int = 2,
                  up: bool = True, steps: int | None = None) -> dict:
    """Kinematic release test: translate `obj` along the axis and look for contact.

    A boolean-difference cavity can be watertight, correctly sized and still
    impossible to open; only a swept-interference test catches that. Returns the
    first interfering step (None if the object clears completely).
    """
    n = piece.shape[axis] if steps is None else steps
    first, worst = None, 0
    for s in range(1, n + 1):
        shifted = np.roll(obj, s if up else -s, axis=axis)
        sl = [slice(None)] * 3
        sl[axis] = slice(0, s) if up else slice(obj.shape[axis] - s, obj.shape[axis])
        shifted[tuple(sl)] = False
        hits = int((shifted & piece).sum())
        if hits > 0:
            worst = max(worst, hits)
            if first is None:
                first = s
    return {"clears": first is None, "first_interference_step": first,
            "max_interfering_voxels": worst, "steps_tested": n}


def volume_balance(box: np.ndarray, parts: dict, pitch: float) -> dict:
    """Exact partition check: the pieces plus the object must tile the mould block.

    Done on occupancy, where a partition is exact by construction, so any non-zero
    residual or overlap is a coding error rather than discretisation noise. Mesh
    volumes are reported separately because those DO carry marching-cubes error.
    """
    names = list(parts)
    union = np.zeros_like(box)
    overlap = 0
    for k in names:
        overlap += int((union & parts[k]).sum())
        union |= parts[k]
    v = pitch ** 3
    return {
        "box_mm3": float(box.sum() * v),
        "parts_mm3": {k: float(parts[k].sum() * v) for k in names},
        "sum_parts_mm3": float(sum(parts[k].sum() for k in names) * v),
        "missing_mm3": float((box & ~union).sum() * v),
        "outside_box_mm3": float((union & ~box).sum() * v),
        "overlap_mm3": float(overlap * v),
        "residual_mm3": float(((box.sum() - union.sum()) if True else 0) * v),
        "residual_frac": float(abs(box.sum() - union.sum()) / max(box.sum(), 1)),
        "exact": bool(overlap == 0 and (box & ~union).sum() == 0
                      and (union & ~box).sum() == 0),
    }


def mesh_report(m: trimesh.Trimesh) -> dict:
    return {"watertight": bool(m.is_watertight), "winding_consistent": bool(m.is_winding_consistent),
            "volume_mm3": float(m.volume), "area_mm2": float(m.area),
            "euler_number": int(m.euler_number), "bodies": int(m.body_count),
            "faces": int(len(m.faces)), "vertices": int(len(m.vertices))}


# --------------------------------------------------------------------------
# Structural sizing of the mould wall itself
# --------------------------------------------------------------------------
def wall_deflection(q_kPa: float, span_mm: float, t_mm: float, *,
                    E_GPa: float = 2.0, nu: float = 0.4) -> dict:
    """Centre deflection of a simply-supported square mould wall panel.

    Kirchhoff plate, uniform pressure: w = 0.00406 q a^4 / D, D = E t^3/(12(1-nu^2)).
    The load is the wet mix's hydrostatic head times a compaction/tamping factor;
    the deflection target is what sets the wall, because a mould that bulges casts
    an out-of-tolerance wall thickness, and wall thickness is the parameter the
    drying and oxygen models are most sensitive to.
    """
    E = E_GPa * 1e9
    D = E * (t_mm * 1e-3) ** 3 / (12 * (1 - nu ** 2))
    w = 0.00406 * (q_kPa * 1e3) * (span_mm * 1e-3) ** 4 / D
    return {"q_kPa": q_kPa, "span_mm": span_mm, "t_mm": t_mm, "D_Nm": D,
            "w_center_mm": w * 1e3}


def mix_pressure(depth_mm: float, *, rho_kg_m3: float = 1890.0,
                 compaction_factor: float = 10.0) -> dict:
    """Design pressure on the mould wall from the wet granular mix."""
    p = rho_kg_m3 * 9.81 * (depth_mm * 1e-3) / 1e3
    return {"rho_kg_m3": rho_kg_m3, "depth_mm": depth_mm, "p_static_kPa": p,
            "compaction_factor": compaction_factor,
            "p_design_kPa": p * compaction_factor}


# --------------------------------------------------------------------------
# Mould block envelopes
# --------------------------------------------------------------------------
def cup_flange_block(X, Y, Z, *, r_cup: float, z_lo: float, z_hi: float,
                     parting: float, flange: float, flange_t: float,
                     square: bool = False, half_x: float = 0.0,
                     half_y: float = 0.0) -> np.ndarray:
    """Mould-block envelope: a cup (cylinder or box) plus a parting-plane flange.

    The flange is what makes the mould clampable and is where the registration
    keys and bolts live, so it must be thick enough to house a key socket without
    breaking through to the outside face.
    """
    if square:
        cup = sdf.sd_box(X, Y, Z, half_x + 0.0, half_y + 0.0, (z_hi - z_lo) / 2,
                         center=(0.0, 0.0, (z_hi + z_lo) / 2))
        fl = sdf.sd_box(X, Y, Z, half_x + flange, half_y + flange, flange_t,
                        center=(0.0, 0.0, parting))
    else:
        cup = sdf.sd_cylinder_z(X, Y, Z, r_cup, (z_hi - z_lo) / 2,
                                center=(0.0, 0.0, (z_hi + z_lo) / 2))
        fl = sdf.sd_cylinder_z(X, Y, Z, r_cup + flange, flange_t,
                               center=(0.0, 0.0, parting))
    return np.minimum(cup, fl)


# --------------------------------------------------------------------------
# Assembly
# --------------------------------------------------------------------------
def assemble(*, obj_occ, cavity_occ, block_occ, X, Y, Z, origin, pitch,
             parting: float, mp: MouldParams, r_ref: float,
             gate_specs=(), drain_specs=(), square: bool = False,
             half_x: float = 0.0, half_y: float = 0.0,
             key_xy=None, bolt_xy=None) -> dict:
    """Cut a two-part mould out of `block_occ` and account for every void.

    Verification strategy: rather than trusting a hand-written list of the volumes
    that ought to be missing, the residual is computed as

        residual = block - lower - upper - cavity

    and then ATTRIBUTED by intersecting it with each named feature. Any void the
    named features cannot explain shows up as `unattributed_mm3`, which is the
    number that actually catches a mis-signed boolean or a feature that silently
    cut through a wall. A hand-tallied balance cannot do that, because a wrong
    boolean changes both sides of the tally at once.
    """
    origin = np.asarray(origin, float)
    v = pitch ** 3
    k_part = int(round((parting - origin[2]) / pitch))
    below = np.zeros(block_occ.shape, bool)
    below[:, :, :k_part] = True
    L0 = block_occ & below
    U0 = block_occ & ~below

    r_key = r_ref + mp.key_r_frac * mp.flange
    r_bolt = r_ref + mp.bolt_r_frac * mp.flange
    bolt_ang = [60.0 + i * 360.0 / mp.bolt_count for i in range(mp.bolt_count)]
    if key_xy is None:
        key_xy = (ring_positions_rect(mp.key_count, mp.key_angles_deg,
                                      half_x + mp.key_r_frac * mp.flange,
                                      half_y + mp.key_r_frac * mp.flange)
                  if square else
                  ring_positions(mp.key_count, mp.key_angles_deg, r_key))
    if bolt_xy is None:
        bolt_xy = (ring_positions_rect(mp.bolt_count, bolt_ang,
                                       half_x + mp.bolt_r_frac * mp.flange,
                                       half_y + mp.bolt_r_frac * mp.flange)
                   if square else
                   ring_positions(mp.bolt_count, bolt_ang, r_bolt))
    key_xy, bolt_xy = list(key_xy), list(bolt_xy)

    # registration keys: truncated cones on the lower half, sockets in the upper
    dowel = np.zeros(block_occ.shape, bool)
    socket = np.zeros(block_occ.shape, bool)
    for (kx, ky) in key_xy:
        dowel |= frustum_field(X, Y, Z, r_base=mp.key_base_d / 2,
                               r_top=mp.key_top_d / 2, z0=parting,
                               z1=parting + mp.key_h, center=(kx, ky)) <= 0
        socket |= frustum_field(X, Y, Z, r_base=mp.key_base_d / 2 + mp.key_clear,
                                r_top=mp.key_top_d / 2 + mp.key_clear, z0=parting,
                                z1=parting + mp.key_h + mp.key_clear,
                                center=(kx, ky)) <= 0
    dowel &= U0
    socket &= U0

    # clamping bolts: through both halves, in the flange
    bolts = np.zeros(block_occ.shape, bool)
    for (bx, by) in bolt_xy:
        bolts |= sdf.sd_cylinder_z(X, Y, Z, mp.bolt_d / 2, 1e4,
                                   center=(bx, by, parting)) <= 0

    # feed / vent gates: radial channels at the parting plane (aggregate class)
    gates = np.zeros(block_occ.shape, bool)
    for spec in gate_specs:
        gates |= spec(X, Y, Z) <= 0
    gates &= U0

    # liquid-only drains through the lower half (they bridge by design)
    drains = np.zeros(block_occ.shape, bool)
    for spec in drain_specs:
        drains |= spec(X, Y, Z) <= 0
    drains &= L0

    lower = (L0 & ~cavity_occ & ~drains & ~bolts) | (dowel & ~cavity_occ)
    upper = U0 & ~cavity_occ & ~gates & ~bolts & ~socket

    cav_in = cavity_occ & block_occ
    residual = block_occ & ~lower & ~upper & ~cav_in
    named = {"drains": drains, "bolts": bolts, "gates": gates,
             "key_clearance": socket & ~dowel}
    attributed = np.zeros_like(residual)
    attr = {}
    for k, feat in named.items():
        hit = residual & feat & ~attributed
        attr[k + "_mm3"] = float(hit.sum() * pitch ** 3)
        attributed |= hit
    unattributed = residual & ~attributed

    balance = {
        "block_mm3": float(block_occ.sum() * v),
        "lower_mm3": float(lower.sum() * v),
        "upper_mm3": float(upper.sum() * v),
        "cavity_in_block_mm3": float(cav_in.sum() * v),
        "residual_void_mm3": float(residual.sum() * v),
        **attr,
        "unattributed_mm3": float(unattributed.sum() * v),
        "sum_all_mm3": float((lower.sum() + upper.sum() + cav_in.sum()
                              + residual.sum()) * v),
        "overlap_lower_upper_mm3": float((lower & upper).sum() * v),
        "overlap_lower_cavity_mm3": float((lower & cav_in).sum() * v),
        "overlap_upper_cavity_mm3": float((upper & cav_in).sum() * v),
        "outside_block_mm3": float(((lower | upper) & ~block_occ).sum() * v),
    }
    balance["closure_residual_mm3"] = balance["sum_all_mm3"] - balance["block_mm3"]
    balance["closure_residual_frac"] = (balance["closure_residual_mm3"]
                                       / max(balance["block_mm3"], 1e-9))
    balance["exact"] = bool(
        abs(balance["closure_residual_mm3"]) < 1e-6
        and balance["overlap_lower_upper_mm3"] == 0.0
        and balance["overlap_lower_cavity_mm3"] == 0.0
        and balance["overlap_upper_cavity_mm3"] == 0.0
        and balance["outside_block_mm3"] == 0.0
        and balance["unattributed_mm3"] == 0.0)

    return {"lower": lower, "upper": upper, "cavity": cav_in, "dowel": dowel,
            "socket": socket, "bolts": bolts, "gates": gates, "drains": drains,
            "L0": L0, "U0": U0, "k_part": k_part, "balance": balance,
            "r_key": r_key, "r_bolt": r_bolt,
            "key_xy": key_xy, "bolt_xy": bolt_xy,
            "key_volume_mm3": float(dowel.sum() * v),
            "key_volume_nominal_mm3": float(
                mp.key_count * np.pi * mp.key_h / 3.0
                * ((mp.key_base_d / 2) ** 2 + (mp.key_base_d / 2) * (mp.key_top_d / 2)
                   + (mp.key_top_d / 2) ** 2)),
            "keys_chiral": keys_are_chiral_xy(key_xy, rectangular=square)}


def occ_to_mesh(occ: np.ndarray, origin, pitch: float, *, largest: bool = True):
    """Mesh an occupancy set, keeping the largest body and repairing normals."""
    d = sdf.signed_distance_from_binary(occ, pitch)
    m = sdf.mesh_field(d, np.asarray(origin, float), pitch)
    if largest and m.body_count > 1:
        m = max(m.split(only_watertight=False), key=lambda x: x.volume)
    m.fill_holes()
    trimesh.repair.fix_normals(m)
    return m


